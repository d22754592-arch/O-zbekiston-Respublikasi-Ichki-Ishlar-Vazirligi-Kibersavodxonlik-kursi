export function getTranslation(lang: Language, key: keyof typeof translations['uz'], params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.uz;
  let text = (dict as any)[key] || (translations.uz as any)[key] || key;
  
  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }
  
  return text;
}
